<?php
/**
 * index.php — single entry point (front controller) of Win Wselna?
 * Every page is reached through index.php?action=...  The router asks a Controller
 * for the data, then loads the matching View. Views never touch the database.
 */
declare(strict_types=1);

// --------------------------------------------------------------
// 0. No action given (e.g. http://localhost/winwselna/) → no page is shown directly:
//    the visitor is sent to View/, which only lists the frontoffice/ and backoffice/ folders.
// --------------------------------------------------------------
if (!isset($_GET['action'])) {
    header('Location: View/');
    exit;
}

// --------------------------------------------------------------
// 1. Secure session configuration (ini_set BEFORE session_start)
// --------------------------------------------------------------
ini_set('session.use_strict_mode', '1');    // reject session ids not generated by the server
ini_set('session.cookie_httponly', '1');    // cookie invisible to JavaScript (anti session theft via XSS)
ini_set('session.cookie_samesite', 'Lax');  // cookie not sent by third-party sites (anti CSRF)
ini_set('session.use_only_cookies', '1');
// ini_set('session.cookie_secure', '1');   // enable when the site is served over HTTPS
session_start();

require_once __DIR__ . '/Config/config.php';

// --------------------------------------------------------------
// 2. Session expiration after 30 minutes of inactivity
// --------------------------------------------------------------
if (isset($_SESSION['last_activity']) && (time() - $_SESSION['last_activity'] > SESSION_LIFETIME)) {
    $_SESSION = [];
    session_destroy();
    session_start();
    flash('error', 'Your session expired after 30 minutes of inactivity. Please log in again.');
}
$_SESSION['last_activity'] = time();

// --------------------------------------------------------------
// 3. HTTP security headers
// --------------------------------------------------------------
header('X-Frame-Options: DENY');                                   // anti clickjacking
header('X-Content-Type-Options: nosniff');                         // no MIME sniffing
header('Referrer-Policy: strict-origin-when-cross-origin');
header("Content-Security-Policy: default-src 'self'; script-src 'self'; "
     . "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src 'self' https://fonts.gstatic.com; "
     . "img-src 'self' data:; form-action 'self'; frame-ancestors 'none'; base-uri 'self'");

// --------------------------------------------------------------
// 4. Controllers
// --------------------------------------------------------------
require_once __DIR__ . '/Controller/AuthController.php';
require_once __DIR__ . '/Controller/UserController.php';
require_once __DIR__ . '/Controller/StatsController.php';

$authController = new AuthController();
$csrfToken = $authController->getCsrfToken();
$isPost = ($_SERVER['REQUEST_METHOD'] ?? 'GET') === 'POST';
$governorates = AuthController::GOVERNORATES;

/** Redirect helper */
function go(string $action, array $params = []): void
{
    header('Location: ' . url($action, $params));
    exit;
}

// Back-office pages that only render their template for now (each module owner connects them later)
$adminModulePages = [
    'admin_categories'     => ['file' => 'categories.php',     'roles' => ['ADMIN']],
    'admin_articles'       => ['file' => 'articles.php',       'roles' => ['ADMIN']],
    'admin_projects'       => ['file' => 'projects.php',       'roles' => ['ADMIN']],
    'admin_milestones'     => ['file' => 'milestones.php',     'roles' => ['ADMIN', 'AGENT']],
    'admin_reclamations'   => ['file' => 'reclamations.php',   'roles' => ['ADMIN', 'AGENT']],
    'admin_lines'          => ['file' => 'lines.php',          'roles' => ['ADMIN']],
    'admin_tickets'        => ['file' => 'tickets.php',        'roles' => ['ADMIN', 'AGENT']],
    'admin_events'         => ['file' => 'events.php',         'roles' => ['ADMIN']],
    'admin_participations' => ['file' => 'participations.php', 'roles' => ['ADMIN']],
    'admin_job_offers'     => ['file' => 'job-offers.php',     'roles' => ['ADMIN']],
    'admin_applications'   => ['file' => 'applications.php',   'roles' => ['ADMIN']],
];
// Public pages of the site (no login needed to read them)
$publicPages = ['news', 'article', 'projects', 'project', 'reclamations', 'transport', 'events', 'jobs'];

// --------------------------------------------------------------
// 5. Routing
// --------------------------------------------------------------
$action = (string) ($_GET['action'] ?? 'home');

switch ($action) {

    // ---------------- HOME (public) ----------------
    case 'home':
        $home = (new StatsController())->home();
        require __DIR__ . '/View/frontoffice/home.php';
        break;

    // ---------------- REGISTER (Create) ----------------
    case 'register':
        if (AuthController::isAuthenticated()) {
            go(AuthController::homeFor(AuthController::currentRole()));
        }
        $errors = [];
        $old = [];
        if ($isPost) {
            $errors = $authController->register($_POST);
            $old = ['full_name' => $_POST['full_name'] ?? '', 'email' => $_POST['email'] ?? '',
                    'phone' => $_POST['phone'] ?? '', 'governorate' => $_POST['governorate'] ?? ''];
            if (!$errors) {
                flash('success', 'Account created successfully, you can now log in.');
                go('login', ['registered' => 1]);
            }
        }
        require __DIR__ . '/View/frontoffice/register.php';
        break;

    // ---------------- LOGIN (one login page for every role) ----------------
    case 'login':
        if (AuthController::isAuthenticated()) {
            go(AuthController::homeFor(AuthController::currentRole()));
        }
        $errors = [];
        $old = [];
        if ($isPost) {
            $errors = $authController->login($_POST);
            $old = ['email' => $_POST['email'] ?? ''];
            if (!$errors) {
                // role read from the database → staff to the dashboard, clients to the site
                go(AuthController::homeFor($_SESSION['role'] ?? null));
            }
        }
        $csrfToken = $authController->getCsrfToken();
        require __DIR__ . '/View/frontoffice/login.php';
        break;

    // ---------------- LOGOUT ----------------
    case 'logout':
        $authController->logout();
        session_start();
        flash('success', 'You have been logged out.');
        go('login');

    // ---------------- MY SPACE (client: Read own account + activity) ----------------
    case 'account':
        AuthController::requireAuth();
        if (AuthController::isStaff()) {
            go('admin_profile');
        }
        $user = $authController->currentUser();
        $activity = (new StatsController())->mySpace($user->getId());
        $errors = $_SESSION['form_errors'] ?? [];
        $old = $_SESSION['form_old'] ?? [];
        $openTab = $_SESSION['open_tab'] ?? '';
        unset($_SESSION['form_errors'], $_SESSION['form_old'], $_SESSION['open_tab']);
        require __DIR__ . '/View/frontoffice/account.php';
        break;

    // ---------------- PROFILE: Update / change password / Delete (every role) ----------------
    case 'profile_update':
    case 'password_update':
    case 'account_delete':
        AuthController::requireAuth();
        $user = $authController->currentUser();
        $back = AuthController::isStaff() ? 'admin_profile' : 'account';
        if (!$isPost) {
            go($back);
        }
        if ($action === 'profile_update') {
            $errors = $authController->updateProfile($user, $_POST);
            $ok = 'Your profile has been updated.';
        } elseif ($action === 'password_update') {
            $errors = $authController->changePassword($user, $_POST);
            $ok = 'Your password has been changed.';
        } else {
            $errors = $authController->deleteAccount($user, $_POST);
            if (!$errors) {
                session_start();
                flash('success', 'Your account has been deleted. Goodbye!');
                go('home');
            }
            $ok = '';
        }
        if ($errors) {
            $_SESSION['form_errors'] = $errors;
            $_SESSION['form_old'] = array_diff_key($_POST, array_flip(['password', 'password_confirm', 'current_password', 'new_password', 'new_password_confirm', 'delete_password', 'csrf_token']));
            $_SESSION['open_tab'] = $action;
            flash('error', reset($errors));
        } else {
            flash('success', $ok);
        }
        go($back);

    // ---------------- DASHBOARD (ADMIN + AGENT) ----------------
    case 'admin':
        if (!AuthController::isAuthenticated()) {
            flash('error', 'The back office is reserved to agents and administrators: please log in first.');
            go('login');
        }
        AuthController::requireRole(AuthController::STAFF_ROLES);
        $user = $authController->currentUser();
        $stats = (new StatsController())->dashboard();
        require __DIR__ . '/View/backoffice/dashboard.php';
        break;

    // ---------------- STAFF PROFILE (ADMIN + AGENT) ----------------
    case 'admin_profile':
        AuthController::requireRole(AuthController::STAFF_ROLES);
        $user = $authController->currentUser();
        $errors = $_SESSION['form_errors'] ?? [];
        $old = $_SESSION['form_old'] ?? [];
        $openTab = $_SESSION['open_tab'] ?? '';
        unset($_SESSION['form_errors'], $_SESSION['form_old'], $_SESSION['open_tab']);
        require __DIR__ . '/View/backoffice/profile.php';
        break;

    // ---------------- USERS: Read / search (ADMIN only) ----------------
    case 'admin_users':
        AuthController::requireRole(['ADMIN']);
        $user = $authController->currentUser();
        $userController = new UserController();
        $search = trim((string) ($_GET['q'] ?? ''));
        $roleFilter = (string) ($_GET['role'] ?? '');
        $users = $userController->getUsers($search, $roleFilter);
        $counts = ['ALL' => $userController->countAllUsers(), 'CLIENT' => $userController->countByRole('CLIENT'),
                   'AGENT' => $userController->countByRole('AGENT'), 'ADMIN' => $userController->countByRole('ADMIN')];
        $errors = $_SESSION['form_errors'] ?? [];
        $old = $_SESSION['form_old'] ?? [];
        unset($_SESSION['form_errors'], $_SESSION['form_old']);
        require __DIR__ . '/View/backoffice/users.php';
        break;

    // ---------------- USERS: Create / Update / Delete (ADMIN only, POST) ----------------
    case 'admin_user_save':
    case 'admin_user_delete':
        AuthController::requireRole(['ADMIN']);
        $user = $authController->currentUser();
        if (!$isPost) {
            go('admin_users');
        }
        $userController = new UserController();
        $id = (int) ($_POST['id'] ?? 0);
        if ($action === 'admin_user_delete') {
            $errors = $userController->delete($id, $_POST, $user->getId());
            $ok = 'The account has been deleted.';
        } elseif ($id > 0) {
            $errors = $userController->update($id, $_POST, $user->getId());
            $ok = 'The account has been updated.';
        } else {
            $errors = $userController->create($_POST);
            $ok = 'The account has been created.';
        }
        if ($errors) {
            $_SESSION['form_errors'] = $errors;
            $_SESSION['form_old'] = array_diff_key($_POST, array_flip(['password', 'password_confirm', 'csrf_token']));
            flash('error', reset($errors));
        } else {
            flash('success', $ok);
        }
        go('admin_users');

    default:
        // Module pages of the back office (template only for now)
        if (isset($adminModulePages[$action])) {
            AuthController::requireRole($adminModulePages[$action]['roles']);
            $user = $authController->currentUser();
            require __DIR__ . '/View/backoffice/' . $adminModulePages[$action]['file'];
            break;
        }
        // Public module pages of the site
        if (in_array($action, $publicPages, true)) {
            require __DIR__ . '/View/frontoffice/' . $action . '.php';
            break;
        }
        http_response_code(404);
        require __DIR__ . '/View/errors/404.php';
        break;
}
